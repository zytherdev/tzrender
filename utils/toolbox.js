let currentLanguage = 'en';
const byId = (id) => document.getElementById(id);

export async function mountToolbox() {
  const mount = byId('toolboxMount');
  if (!mount) return;
  const response = await fetch('/utils/toolbox.html');
  if (!response.ok) throw new Error(`Toolbox markup failed to load (${response.status})`);
  mount.innerHTML = await response.text();
  bindTools();
  setToolboxLanguage(localStorage.getItem('lang') || 'en');
}

export function setToolboxLanguage(language) {
  currentLanguage = COPY[language] ? language : 'en';
  const words = COPY[currentLanguage];
  document.querySelectorAll('[data-tool-copy]').forEach((element) => {
    const value = words[element.dataset.toolCopy];
    if (value) element.textContent = value;
  });
  const html = byId('playgroundHtml');
  const js = byId('playgroundJs');
  if (html && !html.dataset.userEdited) {
    const examples = {
      en: '<main class="card"><span class="badge">HELLO, WEB</span><h1>Your idea starts here.</h1><p>Change this code and watch it come alive.</p><button id="helloButton">Try me</button></main>',
      pt: '<main class="card"><span class="badge">OLÁ, WEB</span><h1>Sua ideia começa aqui.</h1><p>Edite este código e veja a mágica acontecer.</p><button id="helloButton">Clique aqui</button></main>',
      es: '<main class="card"><span class="badge">HOLA, WEB</span><h1>Tu idea empieza aquí.</h1><p>Edita este código y mira cómo cobra vida.</p><button id="helloButton">Pruébame</button></main>'
    };
    html.value = examples[currentLanguage];
  }
  if (js && !js.dataset.userEdited) {
    const messages = { en: "alert('You just made your first interaction!');", pt: "alert('Você criou sua primeira interação!');", es: "alert('¡Acabas de crear tu primera interacción!');" };
    js.value = `document.querySelector('#helloButton').addEventListener('click', () => {\n  ${messages[currentLanguage]}\n});`;
  }
  const starterName = byId('starterName');
  const starterLang = byId('starterLang');
  if (starterName && !starterName.dataset.userEdited) {
    starterName.value = { en: 'My first website', pt: 'Meu primeiro site', es: 'Mi primer sitio web' }[currentLanguage];
  }
  if (starterLang && !starterLang.dataset.userEdited) starterLang.value = currentLanguage;
  refreshStarter();
  refreshPlayground();
  window.dispatchEvent(new CustomEvent('tzrender:language-change', { detail: { language: currentLanguage } }));
}

export function getToolboxCopy(key) {
  return COPY[currentLanguage][key] || COPY.en[key] || key;
}

function bindTools() {
  ['starterName', 'starterLang'].forEach((id) => byId(id).addEventListener('input', (event) => {
    event.currentTarget.dataset.userEdited = 'true';
    refreshStarter();
  }));
  ['gradientStart', 'gradientEnd', 'gradientAngle'].forEach((id) => byId(id).addEventListener('input', refreshGradient));
  ['shadowX', 'shadowY', 'shadowBlur', 'shadowSpread'].forEach((id) => byId(id).addEventListener('input', refreshShadow));
  ['contrastText', 'contrastBg'].forEach((id) => byId(id).addEventListener('input', refreshContrast));
  ['playgroundHtml', 'playgroundCss', 'playgroundJs'].forEach((id) => {
    byId(id).addEventListener('input', (event) => {
      event.currentTarget.dataset.userEdited = 'true';
      schedulePreview();
    });
  });
  document.querySelectorAll('[data-copy-target]').forEach((button) => {
    button.addEventListener('click', () => copyCode(button.dataset.copyTarget, button));
  });
  refreshStarter();
  refreshGradient();
  refreshShadow();
  refreshContrast();
  refreshPlayground();
}

function escapeHtml(value) {
  return value.replace(/[&<>"']/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character]);
}

function refreshStarter() {
  const output = byId('starterOutput');
  if (!output) return;
  const title = escapeHtml(byId('starterName').value.trim() || 'My first website');
  const language = byId('starterLang').value;
  const greeting = COPY[language]?.starterGreeting || COPY.en.starterGreeting;
  output.textContent = `<!doctype html>\n<html lang="${language}">\n<head>\n  <meta charset="UTF-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1.0">\n  <meta name="description" content="A simple starter page">\n  <title>${title}</title>\n  <style>\n    * { box-sizing: border-box; }\n    body { margin: 0; min-height: 100vh; display: grid; place-items: center; padding: 2rem; font-family: system-ui, sans-serif; color: #211b38; background: #f4f2ff; }\n    main { width: min(100%, 38rem); padding: 2.5rem; border-radius: 1.5rem; background: white; box-shadow: 0 1rem 3rem #34246a22; }\n    button { padding: .8rem 1rem; border: 0; border-radius: .75rem; color: white; background: #7454df; cursor: pointer; }\n  </style>\n</head>\n<body>\n  <main>\n    <h1>${title}</h1>\n    <p>${greeting}</p>\n    <button id="helloButton">Click me</button>\n  </main>\n  <script>\n    document.querySelector('#helloButton').addEventListener('click', () => {\n      alert('It works!');\n    });\n  </script>\n</body>\n</html>`;
}

function refreshGradient() {
  const start = byId('gradientStart').value;
  const end = byId('gradientEnd').value;
  const angle = byId('gradientAngle').value;
  const gradient = `linear-gradient(${angle}deg, ${start}, ${end})`;
  byId('gradientAngleValue').value = `${angle}°`;
  byId('gradientPreview').style.background = gradient;
  byId('gradientOutput').textContent = `background: ${gradient};`;
}

function refreshShadow() {
  const x = Number(byId('shadowX').value);
  const y = Number(byId('shadowY').value);
  const blur = Number(byId('shadowBlur').value);
  const spread = Number(byId('shadowSpread').value);
  byId('shadowXValue').value = `${x}px`;
  byId('shadowYValue').value = `${y}px`;
  byId('shadowBlurValue').value = `${blur}px`;
  byId('shadowSpreadValue').value = `${spread}px`;
  const shadow = `${x}px ${y}px ${blur}px ${spread}px rgba(37, 28, 72, 0.16)`;
  byId('shadowSample').style.boxShadow = shadow;
  byId('shadowOutput').textContent = `box-shadow: ${shadow};`;
}

function hexRgb(hex) {
  const value = hex.replace('#', '');
  return [0, 2, 4].map((offset) => parseInt(value.slice(offset, offset + 2), 16) / 255);
}

function luminance(hex) {
  const [r, g, b] = hexRgb(hex).map((channel) => channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function refreshContrast() {
  const text = byId('contrastText').value;
  const background = byId('contrastBg').value;
  const lighter = Math.max(luminance(text), luminance(background));
  const darker = Math.min(luminance(text), luminance(background));
  const ratio = (lighter + 0.05) / (darker + 0.05);
  const passAA = ratio >= 4.5;
  const passAAA = ratio >= 7;
  byId('contrastPreview').style.color = text;
  byId('contrastPreview').style.background = background;
  byId('contrastRatio').textContent = `${ratio.toFixed(2)}:1`;
  const badge = byId('contrastBadge');
  const words = COPY[currentLanguage];
  badge.textContent = passAAA ? words.passAAA : passAA ? words.passAA : words.contrastFail;
  badge.classList.toggle('contrast-pass', passAA);
  badge.classList.toggle('contrast-fail', !passAA);
}

let previewTimer;
function schedulePreview() {
  clearTimeout(previewTimer);
  previewTimer = setTimeout(refreshPlayground, 180);
}

function refreshPlayground() {
  const frame = byId('playgroundPreview');
  if (!frame) return;
  const html = byId('playgroundHtml').value.slice(0, 20000).replace(/<\/style/gi, '<\\/style');
  const css = byId('playgroundCss').value.slice(0, 20000).replace(/<\/style/gi, '<\\/style');
  const js = byId('playgroundJs').value.slice(0, 20000).replace(/<\/script/gi, '<\\/script');
  frame.srcdoc = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; img-src data: https:; style-src 'unsafe-inline'; script-src 'unsafe-inline';"><style>${css}</style></head><body>${html}<script>${js}<\/script></body></html>`;
}

async function copyCode(targetId, button) {
  const text = byId(targetId).textContent;
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const temporary = document.createElement('textarea');
    temporary.value = text;
    temporary.style.position = 'fixed';
    temporary.style.opacity = '0';
    document.body.appendChild(temporary);
    temporary.select();
    const copied = document.execCommand('copy');
    temporary.remove();
    if (!copied) {
      button.textContent = COPY[currentLanguage].statusCopyFailed;
      return;
    }
  }
  button.textContent = COPY[currentLanguage].copiedButton;
  window.setTimeout(() => { button.textContent = COPY[currentLanguage].copyButton; }, 1400);
}
